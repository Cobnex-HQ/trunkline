#!/usr/bin/env python3
"""Prepare, build and install a source checkout on a Mac. No administrator access."""
import argparse
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
ARCH = platform.machine()


def run(*args, **kwargs):
    print('+ ' + ' '.join(map(str, args)), flush=True)
    subprocess.run(list(map(str, args)), cwd=ROOT, check=True, **kwargs)


def doctor():
    if sys.version_info < (3, 10):
        raise RuntimeError('Python 3.10 or newer is required.')
    if platform.system() != 'Darwin':
        raise RuntimeError('The native app requires macOS and full Xcode.')
    missing = [name for name in ['git', 'curl', 'xcodebuild', 'xcodegen', 'cmake', 'pkg-config', 'node', 'npm', 'cargo', 'rustup'] if not shutil.which(name)]
    if missing:
        raise RuntimeError('Missing tools: ' + ', '.join(missing) + '. See README.md; run brew bundle, then rustup default stable.')
    run('xcodebuild', '-version')
    run('xcrun', '--sdk', 'macosx', '--show-sdk-path')
    run('cargo', '--version')


def setup():
    doctor()
    run(sys.executable, 'Scripts/bootstrap.py')
    run('rustup', 'target', 'add', 'aarch64-apple-ios')
    run('cargo', 'fetch', '--locked', '--manifest-path', 'Packages/Transport/Cargo.toml')
    run('xcodegen', 'generate')


def desktop():
    """Always reapply/validate recipes; CMake provides incremental compilation."""
    run(sys.executable, 'Scripts/prepare-desktop-engine.py')
    run(sys.executable, 'Scripts/build-desktop-dependencies.py', ARCH)
    run(sys.executable, 'Scripts/configure-desktop-release.py', ARCH)
    build = ROOT / f'.build/cmake-build-desktop-release-{ARCH}'
    log = ROOT / f'.build/desktop-dev-{ARCH}.log'
    with log.open('w') as stream:
        print(f'Building desktop engine; log: {log}', flush=True)
        run('cmake', '--build', build, '--target', 'sunshine', '-j', str(min(os.cpu_count() or 4, 8)), stdout=stream, stderr=subprocess.STDOUT)
    with log.with_suffix('.web.log').open('w') as stream:
        run('cmake', '--build', build, '--target', 'web-ui', '-j', '2', stdout=stream, stderr=subprocess.STDOUT)
    # Unique validated stage avoids modifying an existing runtime in use by Xcode.
    stage = Path(tempfile.mkdtemp(prefix='desktop-runtime-', dir=ROOT / '.build'))
    stage.rmdir()
    run(sys.executable, 'Scripts/stage-desktop-release.py', '--architectures', ARCH, f'--{ARCH}-log', log, '--output', stage)
    (ROOT / 'Config/Generated.xcconfig').write_text(
        '// Generated by Scripts/dev.py. Local build only.\n'
        f'TRUNKLINE_DESKTOP_RUNTIME = $(SRCROOT)/{stage.relative_to(ROOT)}\n'
        f'ARCHS = {ARCH}\n')
    return stage


def build_mac():
    setup()
    stage = desktop()
    run('xcodebuild', '-quiet', '-project', 'Trunkline.xcodeproj', '-scheme', 'TrunklineHost',
        '-configuration', 'Debug', '-destination', 'generic/platform=macOS',
        '-derivedDataPath', '.build/dev-mac', f'ARCHS={ARCH}', 'ONLY_ACTIVE_ARCH=YES',
        'CODE_SIGN_IDENTITY=-', 'CODE_SIGN_STYLE=Manual', 'DEVELOPMENT_TEAM=',
        'CODE_SIGNING_ALLOWED=YES', 'build', env={**os.environ, 'TRUNKLINE_DESKTOP_RUNTIME': str(stage)})
    app = ROOT / '.build/dev-mac/Build/Products/Debug/Trunkline.app'
    run(sys.executable, 'Scripts/distribution.py', 'verify', '--app', app)
    return app


def install_app(source, target, processes=None):
    """Copy before replacement and retain one previous version for rollback."""
    if processes is None:
        processes = subprocess.check_output(['ps', '-axo', 'command='], text=True)
    if str(target / 'Contents/MacOS') in processes:
        raise RuntimeError(f'Quit {target.name} before installing. The running app was left untouched.')
    target.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.trunkline-install-', dir=target.parent) as temporary:
        staged = Path(temporary) / target.name
        shutil.copytree(source, staged, symlinks=True)
        previous = target.with_name('Trunkline.previous.app')
        if previous.exists():
            shutil.rmtree(previous)
        if target.exists():
            target.rename(previous)
        try:
            staged.rename(target)
        except OSError:
            if previous.exists() and not target.exists():
                previous.rename(target)
            raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['doctor', 'setup', 'build', 'install', 'ios', 'test'])
    parser.add_argument('--destination', type=Path, default=Path.home() / 'Applications/Trunkline.app', help='Mac install location')
    args = parser.parse_args()
    if args.command == 'doctor': doctor()
    elif args.command == 'setup': setup()
    elif args.command in ('build', 'install'):
        app = build_mac()
        if args.command == 'install':
            install_app(app, args.destination.expanduser().absolute())
            print(f'Installed {args.destination}. Open it and complete macOS permissions once.')
        else: print(app)
    elif args.command == 'ios':
        setup()
        run('open', 'Trunkline.xcodeproj')
        print('Select Trunkline, your device and your own signing team in Xcode.')
    else:
        run(sys.executable, '-m', 'unittest', 'discover', '-s', 'Tests/Tooling')
        run('swift', 'test', '--package-path', 'Packages/Core', '--scratch-path', '.build/core', '--disable-sandbox')
        run('cargo', 'test', '--locked', '--manifest-path', 'Packages/Transport/Cargo.toml')


if __name__ == '__main__':
    try: main()
    except (RuntimeError, ValueError, OSError, subprocess.CalledProcessError) as error:
        sys.exit(str(error))
